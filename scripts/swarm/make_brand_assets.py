"""Generate SWARM Messenger's Android icons from the SWARM mark.

Source: scripts/swarm/brand/swarm-mark.svg, copied verbatim from the SWARM brand kit
(D:/privacy/brand/swarm-mark/dist/swarm-mark.svg, sha256 1daf0ec5...6583, the same file the SWARM
wallet ships as its in-app mark). The mark is the chevron and two wings; it never gets a face.

Writes (idempotent, run from the repository root):
  app/src/main/res/drawable/ic_launcher_background.xml   warm black #0A0908
  app/src/main/res/drawable/ic_launcher_foreground.xml   the mark in honey #F5A623 / amber #E8890C,
                                                         inside the 66 dp adaptive-icon safe zone
  app/src/main/res/drawable/ic_launcher_monochrome.xml   the mark in one colour (themed icons)
  app/src/main/res/mipmap-*/ic_launcher.png              legacy launcher icons for Android 6-7.1
  app/src/main/res/drawable/ic_notification.xml          white status-bar mark (replaces the PNGs)
  app/src/main/res/drawable/ic_signal_logo_large.xml     the in-app logo (release notes avatar, empty
                                                         detail pane); file name kept so no code moves
  app/src/main/res/drawable/ic_signal_logo_small.xml     the small white logo (incoming call screen)
  feature/registration/src/main/res/drawable/swarm_mark.xml  the mark for the welcome and wallet screens

Colours are the brand kit's app-icon tokens (honey, amber-deep) on the style guide's warm black.
Requires Pillow for the PNGs.
"""

import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
SVG = os.path.join(os.path.dirname(__file__), "brand", "swarm-mark.svg")
RES = os.path.join(ROOT, "app", "src", "main", "res")

WARM_BLACK = "#0A0908"
HONEY = "#F5A623"       # the chevron
AMBER = "#E8890C"       # the wings

VIEWBOX_W = 1000.0
VIEWBOX_H = 467.95

HEADER = "<!-- Generated by scripts/swarm/make_brand_assets.py from the SWARM mark. Do not edit by hand. -->\n"


def read_paths():
    with open(SVG, encoding="utf-8") as handle:
        svg = handle.read()
    paths = re.findall(r'<path\s+fill="(#[0-9A-Fa-f]{6})"\s+d="([^"]+)"', svg)
    if len(paths) != 3:
        sys.exit(f"make_brand_assets: expected 3 paths in {SVG}, found {len(paths)}")
    # First path is the chevron, the other two are the wings.
    return [(HONEY if index == 0 else AMBER, data) for index, (_, data) in enumerate(paths)]


def vector(size_dp, viewport, mark_width, colors, background=None, center_y=None):
    """A VectorDrawable with the mark centred, `mark_width` viewport units wide."""
    scale = mark_width / VIEWBOX_W
    height = VIEWBOX_H * scale
    tx = (viewport - mark_width) / 2.0
    cy = viewport / 2.0 if center_y is None else center_y
    ty = cy - height / 2.0
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        HEADER.rstrip(),
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        f'    android:width="{size_dp}dp"',
        f'    android:height="{size_dp}dp"',
        f'    android:viewportWidth="{viewport}"',
        f'    android:viewportHeight="{viewport}">',
    ]
    if background:
        lines += [
            "  <path",
            f'      android:fillColor="{background}"',
            f'      android:pathData="M0,0h{viewport}v{viewport}h-{viewport}z" />',
        ]
    lines += [
        "  <group",
        f'      android:scaleX="{scale:.6f}"',
        f'      android:scaleY="{scale:.6f}"',
        f'      android:translateX="{tx:.4f}"',
        f'      android:translateY="{ty:.4f}">',
    ]
    for color, data in colors:
        lines += [
            "    <path",
            f'        android:fillColor="{color}"',
            f'        android:pathData="{data}" />',
        ]
    lines += ["  </group>", "</vector>", ""]
    return "\n".join(lines)


def mark_vector(width_dp, colors):
    """The mark alone, at its own aspect ratio (for in-app artwork)."""
    height_dp = round(width_dp * VIEWBOX_H / VIEWBOX_W, 2)
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        HEADER.rstrip(),
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        f'    android:width="{width_dp}dp"',
        f'    android:height="{height_dp}dp"',
        f'    android:viewportWidth="{VIEWBOX_W:g}"',
        f'    android:viewportHeight="{VIEWBOX_H:g}">',
    ]
    for color, data in colors:
        lines += ["  <path", f'      android:fillColor="{color}"', f'      android:pathData="{data}" />']
    lines += ["</vector>", ""]
    return "\n".join(lines)


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)
    print(f"wrote {os.path.relpath(path, ROOT)}")


# --- PNG rendering (legacy launcher icons) -------------------------------------------------------

def tokens(data):
    return re.findall(r"[MLCZmlcz]|-?\d*\.?\d+(?:e-?\d+)?", data)


def flatten(data, steps=24):
    """Polygons for an SVG path that uses only absolute M, L, C and Z."""
    polygons = []
    current = []
    items = tokens(data)
    i = 0
    command = None
    x = y = 0.0
    while i < len(items):
        item = items[i]
        if re.fullmatch(r"[MLCZmlcz]", item):
            command = item
            i += 1
            if command in "Zz":
                if current:
                    polygons.append(current)
                current = []
            continue
        if command == "M":
            x, y = float(items[i]), float(items[i + 1])
            i += 2
            if current:
                polygons.append(current)
            current = [(x, y)]
            command = "L"
        elif command == "L":
            x, y = float(items[i]), float(items[i + 1])
            i += 2
            current.append((x, y))
        elif command == "C":
            x1, y1, x2, y2, x3, y3 = (float(v) for v in items[i:i + 6])
            i += 6
            for step in range(1, steps + 1):
                t = step / steps
                mt = 1 - t
                px = mt ** 3 * x + 3 * mt ** 2 * t * x1 + 3 * mt * t ** 2 * x2 + t ** 3 * x3
                py = mt ** 3 * y + 3 * mt ** 2 * t * y1 + 3 * mt * t ** 2 * y2 + t ** 3 * y3
                current.append((px, py))
            x, y = x3, y3
        else:
            sys.exit(f"make_brand_assets: unsupported path command {command!r}")
    if current:
        polygons.append(current)
    return polygons


def hex_rgb(color):
    return tuple(int(color[i:i + 2], 16) for i in (1, 3, 5))


def legacy_png(size, colors, path):
    from PIL import Image, ImageDraw

    supersample = 8
    big = size * supersample
    image = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    draw = ImageDraw.Draw(image)
    # Rounded square like the brand kit's store icon, inset the way launcher icons are.
    inset = big * 0.04
    radius = big * 0.22
    draw.rounded_rectangle([inset, inset, big - inset, big - inset], radius=radius, fill=hex_rgb(WARM_BLACK) + (255,))
    mark_width = big * 0.64
    scale = mark_width / VIEWBOX_W
    tx = (big - mark_width) / 2
    ty = (big - VIEWBOX_H * scale) / 2
    for color, data in colors:
        for polygon in flatten(data):
            draw.polygon([(tx + px * scale, ty + py * scale) for px, py in polygon], fill=hex_rgb(color) + (255,))
    image = image.resize((size, size), Image.LANCZOS)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    image.save(path, optimize=True)
    print(f"wrote {os.path.relpath(path, ROOT)} ({size}x{size})")


def main():
    colors = read_paths()
    white = [("#FFFFFFFF", data) for _, data in colors]

    write(os.path.join(RES, "drawable", "ic_launcher_background.xml"),
          '<?xml version="1.0" encoding="utf-8"?>\n' + HEADER +
          '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
          '    android:width="108dp"\n    android:height="108dp"\n'
          '    android:viewportWidth="108"\n    android:viewportHeight="108">\n'
          f'  <path\n      android:fillColor="{WARM_BLACK}"\n      android:pathData="M0,0h108v108h-108z" />\n'
          '</vector>\n')
    # 58 units wide: the mark's corners stay inside the 66 dp safe-zone circle (diagonal ~64).
    write(os.path.join(RES, "drawable", "ic_launcher_foreground.xml"), vector(108, 108, 58, colors))
    write(os.path.join(RES, "drawable", "ic_launcher_monochrome.xml"), vector(108, 108, 58, white))
    write(os.path.join(RES, "drawable", "ic_notification.xml"), vector(24, 24, 22, white))
    write(os.path.join(RES, "drawable", "ic_signal_logo_large.xml"), vector(128, 128, 112, colors))
    write(os.path.join(RES, "drawable", "ic_signal_logo_small.xml"), vector(16, 138, 124, white))

    # The registration module's hero image (welcome and wallet sign-in screens).
    write(os.path.join(ROOT, "feature", "registration", "src", "main", "res", "drawable", "swarm_mark.xml"), mark_vector(240, colors))

    for density, size in (("mdpi", 48), ("hdpi", 72), ("xhdpi", 96), ("xxhdpi", 144), ("xxxhdpi", 192)):
        legacy_png(size, colors, os.path.join(RES, f"mipmap-{density}", "ic_launcher.png"))

    for density in ("mdpi", "hdpi", "xhdpi", "xxhdpi", "xxxhdpi"):
        old = os.path.join(RES, f"drawable-{density}", "ic_notification.png")
        if os.path.exists(old):
            os.remove(old)
            print(f"removed {os.path.relpath(old, ROOT)} (replaced by drawable/ic_notification.xml)")


if __name__ == "__main__":
    main()
